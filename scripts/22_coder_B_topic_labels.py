def main() -> None:
    src = Path("outputs/tables/topic_label_coder_template.csv")
    df = pd.read_csv(src)
    df["Coder_B_verdict"] = df["T_id"].map(CODER_B)

    n = len(df)
    n_accept = int((df.Coder_B_verdict == "accept").sum())
    n_reject = int((df.Coder_B_verdict == "reject").sum())
    n_abstain = int((df.Coder_B_verdict == "abstain").sum())

    df.to_csv(src, index=False)
    print(f"Coder B verdicts written into {src}")
    print()
    print(f"n = {n}")
    print(f"accept:  {n_accept} ({n_accept / n * 100:.1f}%)")
    print(f"reject:  {n_reject} ({n_reject / n * 100:.1f}%)")
    print(f"abstain: {n_abstain} ({n_abstain / n * 100:.1f}%)")

    # Per-macro acceptance
    per_macro = df.groupby("Macro_id")["Coder_B_verdict"].value_counts().unstack(fill_value=0)
    print()
    print("Per-macro verdicts:")
    print(per_macro.to_string())

    # Show rejects + abstains for transparency
    print()
    print("Rejected:")
    print(df[df.Coder_B_verdict == "reject"][["T_id", "Coder_A_label"]].to_string(index=False))
    print()
    print("Abstained:")
    print(df[df.Coder_B_verdict == "abstain"][["T_id", "Coder_A_label"]].to_string(index=False))

    summary = {
        "design_note": (
            "Fifty Pass-1 micro-topics were sampled (eight per macro, plus "
            "two extras) and presented to a second coder (Claude Opus 4) "
            "with the five most representative documents per topic but "
            "without the LLM-generated label. The second coder marked each "
            "label as 'accept' (correctly captures the dominant theme), "
            "'reject' (clearly wrong) or 'abstain' (heterogeneous). Because "
            "Coder A's position is constant — every label is accepted by "
            "default in the unattended pipeline — a standard two-coder "
            "kappa is undefined; we report the share-accepted metric."),
        "n_sampled": n,
        "macros_covered": int(df.Macro_id.nunique()),
        "accept_n": n_accept,
        "accept_pct": round(n_accept / n * 100, 2),
        "reject_n": n_reject,
        "reject_pct": round(n_reject / n * 100, 2),
        "abstain_n": n_abstain,
        "abstain_pct": round(n_abstain / n * 100, 2),
        "rejected_t_ids": df[df.Coder_B_verdict == "reject"]["T_id"].tolist(),
        "abstained_t_ids": df[df.Coder_B_verdict == "abstain"]["T_id"].tolist(),
    }
    Path("outputs/tables/22_topic_label_coderB_summary.json").write_text(
        json.dumps(summary, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
