"""
Inter-coder agreement on the Pass-1 topic labels (reviewer comment 2g).

50 micro-topics from the Pass-1 hierarchy were sampled (8 per macro,
plus 2 extra) and presented to a second coder (Claude Opus 4) with
the topic's five representative documents but *without* the LLM-
generated label. The second coder evaluated whether the LLM label is
an *acceptable* summary of the representative documents.

Three categories:
  'accept'   — the label correctly captures the dominant theme;
  'reject'   — the label is clearly wrong (irrelevant, misleading, or
               contradicted by a majority of the representative docs);
  'abstain'  — the docs are too heterogeneous to call cleanly, or the
               label is ambiguous in scope.

We then compute the share of LLM labels accepted by the second coder
(a percent-agreement reading) and Cohen's kappa against the trivial
baseline of "every LLM label is accepted by default" — which is
exactly the Coder A position. Since Coder A is constant ("accept"),
the standard two-coder Cohen's kappa is undefined; we therefore
report the share-accepted metric only, following the convention used
in the LLM-as-judge literature (Liu et al., 2023, NLLG).
"""
